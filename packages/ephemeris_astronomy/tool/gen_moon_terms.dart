// ZOD-EPH-004 Task 3 Step 1a: generates native/astronomy_c/zodiann_moon_terms.h
// from the vendored, unmodified astronomy-engine source. Run from this
// package's root:
//
//   dart run tool/gen_moon_terms.dart
//
// The table is the 104 `AddSol(...)` rows of `CalcMoon` and the 10 `ADDN(...)`
// rows of `SolarN`, in source order, with their numbers copied as written. It
// is generated and not typed so that no coefficient can be mistyped; a host
// test regenerates it and requires byte equality with the committed header.
import 'dart:convert';
import 'dart:io';

/// The number of `AddSol(...)` rows `CalcMoon` has in the vendored source.
const _expectedAddSolRows = 104;

/// The number of `ADDN(...)` rows `SolarN` has in the vendored source.
const _expectedAddnRows = 10;

final _float = RegExp(r'^[+-]?\d+(\.\d+)?$');
final _int = RegExp(r'^[+-]?\d+$');

/// The text of the header for the rows found in [source] (the contents of
/// upstream `astronomy.c`). Throws [FormatException] for a row with the wrong
/// number of fields or a non-numeric field, and when the number of rows is not
/// the expected 104 and 10.
String generateMoonTermsHeader(
  String source, {
  required String tag,
  required String commit,
  required String sourceBlob,
}) {
  final addSol = <List<String>>[];
  final addn = <List<String>>[];
  final addSolRow = RegExp(r'^\s*AddSol\(ctx,(.*)\);\s*$');
  final addnRow = RegExp(r'^\s*ADDN\((.*)\);\s*$');
  var lineNumber = 0;
  for (final line in const LineSplitter().convert(source)) {
    lineNumber++;
    final solMatch = addSolRow.firstMatch(line);
    if (solMatch != null) {
      addSol.add(
        _fields(solMatch.group(1)!, 8, floats: 4, lineNumber: lineNumber),
      );
      continue;
    }
    final nMatch = addnRow.firstMatch(line);
    if (nMatch != null) {
      addn.add(_fields(nMatch.group(1)!, 5, floats: 1, lineNumber: lineNumber));
    }
  }
  if (addSol.length != _expectedAddSolRows) {
    throw FormatException(
      'expected $_expectedAddSolRows AddSol rows, found ${addSol.length}',
    );
  }
  if (addn.length != _expectedAddnRows) {
    throw FormatException(
      'expected $_expectedAddnRows ADDN rows, found ${addn.length}',
    );
  }
  final out = StringBuffer()
    ..writeln('/*')
    ..writeln(' * GENERATED by tool/gen_moon_terms.dart. DO NOT EDIT.')
    ..writeln(' *')
    ..writeln(' * Source: astronomy-engine $tag (commit $commit),')
    ..writeln(' * astronomy.c (git blob $sourceBlob): the AddSol(...) rows of')
    ..writeln(' * CalcMoon and the ADDN(...) rows of SolarN, in source order,')
    ..writeln(' * numbers copied as written. Regenerate with')
    ..writeln(' * `dart run tool/gen_moon_terms.dart` from')
    ..writeln(' * packages/ephemeris_astronomy; a host test requires this file')
    ..writeln(' * to equal the generator output.')
    ..writeln(' */')
    ..writeln('#ifndef ZODIANN_MOON_TERMS_H')
    ..writeln('#define ZODIANN_MOON_TERMS_H')
    ..writeln()
    ..writeln('typedef struct {')
    ..writeln('  double coeffl, coeffs, coeffg, coeffp;')
    ..writeln('  int p, q, r, s;')
    ..writeln('} zodiann_moon_term_t;')
    ..writeln()
    ..writeln('typedef struct {')
    ..writeln('  double coeffn;')
    ..writeln('  int p, q, r, s;')
    ..writeln('} zodiann_moon_n_term_t;')
    ..writeln()
    ..writeln('#define ZODIANN_MOON_TERM_COUNT ${addSol.length}')
    ..writeln(
      'static const zodiann_moon_term_t '
      'kZodiannMoonTerms[ZODIANN_MOON_TERM_COUNT] = {',
    );
  for (final row in addSol) {
    out.writeln('  {${row.join(', ')}},');
  }
  out
    ..writeln('};')
    ..writeln()
    ..writeln('#define ZODIANN_MOON_N_TERM_COUNT ${addn.length}')
    ..writeln(
      'static const zodiann_moon_n_term_t '
      'kZodiannMoonNTerms[ZODIANN_MOON_N_TERM_COUNT] = {',
    );
  for (final row in addn) {
    out.writeln('  {${row.join(', ')}},');
  }
  out
    ..writeln('};')
    ..writeln()
    ..writeln('#endif /* ZODIANN_MOON_TERMS_H */');
  return out.toString();
}

/// Splits one row's argument text into [count] trimmed numeric tokens, the
/// first [floats] of them decimal numbers and the rest integers.
List<String> _fields(
  String text,
  int count, {
  required int floats,
  required int lineNumber,
}) {
  final parts = text.split(',').map((p) => p.trim()).toList();
  if (parts.length != count) {
    throw FormatException(
      'line $lineNumber: expected $count fields, found ${parts.length}',
      text,
    );
  }
  for (var i = 0; i < parts.length; i++) {
    final ok = (i < floats ? _float : _int).hasMatch(parts[i]);
    if (!ok) {
      throw FormatException(
        'line $lineNumber: field ${i + 1} is not a number',
        parts[i],
      );
    }
  }
  // A leading plus sign is dropped; the number is otherwise as written.
  return [for (final p in parts) p.startsWith('+') ? p.substring(1) : p];
}

Future<void> main() async {
  final packageRoot = Platform.script.resolve('../');
  final native = packageRoot.resolve('../../native/astronomy_c/');
  final manifest = jsonDecode(
    File.fromUri(native.resolve('MANIFEST.json')).readAsStringSync(),
  ) as Map<String, Object?>;
  final files = (manifest['files']! as List<Object?>)
      .cast<Map<String, Object?>>();
  final blob =
      files.firstWhere(
            (f) => (f['path']! as String).endsWith('upstream/astronomy.c'),
          )['blobSha1']!
          as String;
  final header = generateMoonTermsHeader(
    File.fromUri(native.resolve('upstream/astronomy.c')).readAsStringSync(),
    tag: manifest['upstreamTag']! as String,
    commit: manifest['upstreamCommit']! as String,
    sourceBlob: blob,
  );
  // LF line endings, as the committed file is `-text` in .gitattributes.
  File.fromUri(native.resolve('zodiann_moon_terms.h'))
      .writeAsStringSync(header);
}
